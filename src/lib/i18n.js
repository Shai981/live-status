export function detectLanguage() {
  const stored = localStorage.getItem("statusnow_lang");
  if (stored && SUPPORTED_LANGUAGES.find((l) => l.code === stored)) return stored;
  const browser = navigator.language?.split("-")[0];
  if (browser && SUPPORTED_LANGUAGES.find((l) => l.code === browser)) return browser;
  return "en";
}

export function timeAgo(lang, dateStr) {
  if (!dateStr) return "";
  const diff = Date.now() - new Date(dateStr).getTime();
  const mins = Math.floor(diff / 60000);
  const hrs = Math.floor(diff / 3600000);
  const days = Math.floor(diff / 86400000);
  try {
    const rtf = new Intl.RelativeTimeFormat(lang, { numeric: "auto" });
    if (mins < 1) return rtf.format(0, "minute");
    if (mins < 60) return rtf.format(-mins, "minute");
    if (hrs < 24) return rtf.format(-hrs, "hour");
    return rtf.format(-days, "day");
  } catch {
    if (mins < 1) return "just now";
    if (mins < 60) return `${mins}m ago`;
    if (hrs < 24) return `${hrs}h ago`;
    return `${days}d ago`;
  }
}

export function avatarColor(name = "") {
  const colors = ["#ef4444","#f97316","#eab308","#22c55e","#06b6d4","#3b82f6","#8b5cf6","#ec4899","#14b8a6","#f43f5e"];
  let hash = 0;
  for (let i = 0; i < name.length; i++) hash = name.charCodeAt(i) + ((hash << 5) - hash);
  return colors[Math.abs(hash) % colors.length];
}