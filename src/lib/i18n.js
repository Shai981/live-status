export function detectLanguage() {
  const stored = localStorage.getItem("statusnow_lang");
  if (stored && TRANSLATIONS[stored]) return stored;
  const browser = navigator.language?.split("-")[0];
  if (TRANSLATIONS[browser]) return browser;
  return "en";
}

export function t(lang, key, vars = {}) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let str = dict[key] || TRANSLATIONS.en[key] || key;
  Object.entries(vars).forEach(([k, v]) => {
    str = str.replace(`{${k}}`, v);
  });
  return str;
}

export function timeAgo(lang, dateStr) {
  const diff = Date.now() - new Date(dateStr).getTime();
  const mins = Math.floor(diff / 60000);
  if (mins < 1) return t(lang, "justNow");
  if (mins < 60) return t(lang, "minutesAgo", { n: mins });
  const hrs = Math.floor(mins / 60);
  if (hrs < 24) return t(lang, "hoursAgo", { n: hrs });
  return t(lang, "daysAgo", { n: Math.floor(hrs / 24) });
}

